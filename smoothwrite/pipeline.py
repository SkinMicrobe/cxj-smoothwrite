T = TypeVar("T")


class PipelineError(RuntimeError):
    """Error raised with the name of the pipeline stage that failed."""


def _run_stage(name: str, action: Callable[[], T]) -> T:
    """Run one stage and add useful context to any failure."""
    try:
        return action()
    except Exception as exc:
        raise PipelineError(f"Pipeline stage '{name}' failed: {exc}") from exc


def _fallback_article_plan(metadata: PaperMetadata) -> ArticlePlan:
    """Create a conservative article plan without calling an LLM."""
    journal = metadata.journal or "待核查期刊"
    research_object = metadata.research_object or "研究对象"
    title = f"{journal}｜{research_object}：新证据推动理解更新"
    main_thesis = (
        "该研究围绕核心问题提供了新的证据链，但具体机制、适用范围和"
        "结论边界仍需结合原论文人工核查。"
    )
    return ArticlePlan(
        title=title,
        main_thesis=main_thesis,
        old_model="既有认知及其关键缺口需要根据论文背景进一步整理。",
        new_evidence="论文提供的新证据需要结合结果部分和配图进一步整理。",
        new_model="新模型或新理解需要在人工核查证据边界后补充。",
        sections=[
            ArticleSection(
                heading="旧认知留下关键缺口",
                core_point="研究从既有解释无法覆盖的问题出发。",
            ),
            ArticleSection(
                heading="新证据推动理解更新",
                core_point="论文通过新的实验或分析证据回应核心问题。",
                figure_label="配图1",
            ),
            ArticleSection(
                heading="新模型仍有适用边界",
                core_point="研究提出的新理解需要结合限制和未解决问题审视。",
            ),
        ],
    )


def _is_supplementary(asset: FigureAsset) -> bool:
    """Return whether an asset appears to be supplementary or extended data."""
    text = f"{asset.figure_id} {asset.caption or ''}".casefold()
    return "supplement" in text or "extended data" in text


def _fallback_figure_plan(
    article_plan: ArticlePlan,
    figure_assets: list[FigureAsset],
    figure_count: int,
) -> FigurePlan:
    """Select a small set of usable figures without calling an LLM."""
    ordered_assets = sorted(
        figure_assets,
        key=lambda asset: (
            _is_supplementary(asset),
            0 if asset.figure_id.casefold().startswith(("figure 1", "fig. 1", "fig 1")) else 1,
            asset.page_number or 10**9,
        ),
    )
    selected = ordered_assets[:figure_count]
    sections = article_plan.sections
    figures: list[FigurePlanItem] = []

    for index, asset in enumerate(selected, start=1):
        section = sections[min(index, len(sections) - 1)] if sections else None
        image_path = asset.crop_image or asset.page_image
        figures.append(
            FigurePlanItem(
                label=f"配图{index}",
                source_figure=asset.figure_id,
                panels=None,
                placement_after_section=section.heading if section else None,
                reason=(
                    "Fallback selection prioritizes main-text figures and uses "
                    "the best available crop or full-page image."
                ),
                image_path=image_path,
            )
        )

    return FigurePlan(figures=figures)


def _metadata_uncertainty_notes(metadata: PaperMetadata) -> list[str]:
    """Describe metadata fields that still need manual review."""
    notes = list(metadata.notes)
    for field_name in (
        "title",
        "journal",
        "year",
        "month",
        "doi",
        "url",
        "research_object",
        "core_question",
    ):
        if getattr(metadata, field_name) is None:
            notes.append(f"Metadata field '{field_name}' is uncertain or missing.")
    if not metadata.authors:
        notes.append("Metadata field 'authors' is uncertain or missing.")
    return notes


def _build_review_notes(
    metadata: PaperMetadata,
    figure_assets: list[FigureAsset],
) -> tuple[list[str], str]:
    """Build manifest notes and the Markdown review report."""
    notes = _metadata_uncertainty_notes(metadata)
    for asset in figure_assets:
        if asset.crop_confidence in {"failed", "low"}:
            notes.append(
                f"{asset.figure_id}: crop confidence is {asset.crop_confidence}; "
                "review the full-page fallback and crop manually if needed."
            )
    notes.append("Article, article plan, and figure plan were generated by fallback logic.")

    lines = [
        "# smoothwrite 质量检查报告",
        "",
        "## 元信息中不确定的字段",
        "",
    ]
    lines.extend(f"- {note}" for note in _metadata_uncertainty_notes(metadata))
    lines.extend(["", "## Figure 裁剪检查", ""])
    crop_notes = [
        f"- {asset.figure_id}: {asset.crop_confidence}。{'；'.join(asset.notes)}"
        for asset in figure_assets
        if asset.crop_confidence in {"failed", "low"}
    ]
    lines.extend(crop_notes or ["- 未发现失败或低置信度裁剪；仍建议人工检查图像。"])
    lines.extend(
        [
            "",
            "## 文章生成方式",
            "",
            "- 本次文章、文章计划和配图计划均由 fallback 逻辑生成，未调用 LLM。",
            "- 发布前必须人工核查事实、结论边界、配图和文章表达。",
            "",
        ]
    )
    return notes, "\n".join(lines)


def run_pipeline(
    pdf_path: str,
    output_dir: str,
    url: str | None = None,
    journal_hint: str | None = None,
    year_hint: str | None = None,
    month_hint: str | None = None,
    figure_count: int = 4,
    attempt_crop: bool = True,
) -> OutputManifest:
    """Generate all configured artifacts and return their output manifest."""
    if figure_count < 0:
        raise ValueError(f"figure_count must be zero or greater, received: {figure_count}")

    config = _run_stage("load default config", load_default_config)
    output_config = config["output"]
    figure_config = config["figures"]
    output_path = _run_stage(
        "create output directory", lambda: ensure_dir(output_dir).resolve()
    )
    figures_path = _run_stage(
        "create figures directory", lambda: ensure_dir(output_path / "figures")
    )

    parsed_path = output_path / output_config["parsed_pdf_json"]
    metadata_path = output_path / output_config["metadata_json"]
    article_plan_path = output_path / output_config["article_plan_json"]
    figure_plan_path = output_path / output_config["figure_plan_json"]
    article_path = output_path / output_config["article_md"]
    docx_path = output_path / output_config["final_docx"]
    manifest_path = output_path / output_config["manifest_json"]
    review_path = output_path / output_config["review_notes_md"]
    figure_manifest_path = figures_path / "figure_manifest.json"

    parsed_pdf = _run_stage("parse PDF", lambda: parse_pdf(pdf_path))
    _run_stage("save parsed PDF", lambda: model_to_json_file(parsed_pdf, parsed_path))

    metadata = _run_stage(
        "extract metadata",
        lambda: extract_metadata(
            parsed_pdf,
            url=url,
            journal_hint=journal_hint,
            year_hint=year_hint,
            month_hint=month_hint,
        ),
    )
    _run_stage("save metadata", lambda: model_to_json_file(metadata, metadata_path))

    figure_assets = _run_stage(
        "export figures",
        lambda: export_figure_pages(
            pdf_path=pdf_path,
            parsed_pdf=parsed_pdf,
            figures_dir=str(figures_path),
            zoom=float(figure_config["render_zoom"]),
            attempt_crop=attempt_crop,
        ),
    )

    article_plan = _run_stage(
        "generate fallback article plan", lambda: _fallback_article_plan(metadata)
    )
    _run_stage(
        "save article plan", lambda: model_to_json_file(article_plan, article_plan_path)
    )

    figure_plan = _run_stage(
        "generate fallback figure plan",
        lambda: _fallback_figure_plan(article_plan, figure_assets, figure_count),
    )
    _run_stage(
        "save figure plan", lambda: model_to_json_file(figure_plan, figure_plan_path)
    )

    article = _run_stage(
        "generate fallback article",
        lambda: generate_article_markdown(
            metadata=metadata,
            parsed_pdf=parsed_pdf,
            article_plan=article_plan,
            figure_plan=figure_plan,
            llm_client=EchoLLMClient(),
        ),
    )
    _run_stage("save article", lambda: write_text(article_path, article))
    _run_stage(
        "render Word document",
        lambda: render_docx(
            article_md_path=str(article_path),
            figure_plan_path=str(figure_plan_path),
            output_docx_path=str(docx_path),
            base_dir=str(output_path),
        ),
    )

    review_notes, review_markdown = _build_review_notes(metadata, figure_assets)
    _run_stage("save review notes", lambda: write_text(review_path, review_markdown))
    validation_notes = _run_stage(
        "validate outputs", lambda: validate_outputs(str(output_path))
    )
    _run_stage(
        "append validation notes",
        lambda: write_review_notes(str(output_path), validation_notes),
    )
    review_notes.extend(validation_notes)

    manifest = OutputManifest(
        pdf_path=str(Path(pdf_path)),
        output_dir=str(output_path),
        parsed_pdf_json=str(parsed_path),
        article_md=str(article_path),
        final_docx=str(docx_path),
        metadata_json=str(metadata_path),
        article_plan_json=str(article_plan_path),
        figure_plan_json=str(figure_plan_path),
        figures_dir=str(figures_path),
        figure_manifest_json=str(figure_manifest_path),
        review_notes_md=str(review_path),
        output_manifest_json=str(manifest_path),
        review_notes=review_notes,
    )
    _run_stage("save output manifest", lambda: model_to_json_file(manifest, manifest_path))
    return manifest
